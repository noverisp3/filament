#!/usr/bin/env python3
"""Turn Minecraft's data generator reports into Rust source.

Reads `extracted/blocks.json` and `extracted/packets.json` and writes
`src/generated/*.rs`.

The output is generated because the tables are large and mechanical: 1286 blocks
and 35723 block states. Hand-writing those would mean transcribing, and a single
mistyped state id shifts every state after it, which renders as terrain that is
subtly wrong with no error anywhere. Generating them means they always match the
jar they came from.

The block table is what makes a chunk render. A server sends block state IDs, not
block names, so the ID a server assigns has to be the same ID the client expects.
These constants are that agreement.

Usage:
    python tools/build_tables.py
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXTRACTED = ROOT / "extracted"
OUT = ROOT / "src" / "generated"

# Vanilla names are `minecraft:stone`. The namespace is stripped here so the
# constants read as `STONE` rather than `MINECRAFT_STONE`, matching how the
# blocks are referred to everywhere else in the crate.
NAMESPACE = "minecraft:"


def ident(name: str) -> str:
    """`minecraft:oak_stairs` -> `OAK_STAIRS`."""
    if name.startswith(NAMESPACE):
        name = name[len(NAMESPACE) :]
    return "".join(c if c.isalnum() else "_" for c in name).upper()


def load(path: pathlib.Path) -> dict:
    if not path.exists():
        sys.exit(
            f"missing {path}\n"
            "run tools/generate-reports.ps1 first"
        )
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def build_blocks(data: dict) -> str:
    # JSON object order is insertion order, and the data generator writes them in
    # registration order, which is the order block ids were assigned. Sorting by
    # name instead would look tidier and be wrong: the id would stop matching.
    blocks = list(data.values())

    state_count = sum(len(b.get("states", [])) for b in blocks)
    max_id = max(
        (s["id"] for b in blocks for s in b.get("states", [])), default=0
    )

    out = [
        "// @generated by tools/build_tables.py from extracted/blocks.json.",
        "// Do not edit: regenerate with `python tools/build_tables.py`.",
        "//",
        f"// {len(blocks)} blocks, {state_count} block states, highest id {max_id}.",
        "//",
        "// These ids are a wire contract with the client. A server that sends the",
        "// wrong id for a block renders the wrong block, without erroring.",
        "",
        "/// Number of blocks in the registry.",
        f"pub const BLOCK_COUNT: u16 = {len(blocks)};",
        "",
        "/// Number of distinct block states across all blocks.",
        f"pub const BLOCK_STATE_COUNT: u32 = {state_count};",
        "",
        "/// A single property and the value this state holds for it.",
        "pub type Property = (&'static str, &'static str);",
        "",
        "/// One of a block's states.",
        "pub struct BlockState {",
        "    /// The id the client knows this state by. This is what goes on the",
        "    /// wire; the property values are only used to look a state up.",
        "    pub id: u32,",
        "    /// Empty for the many blocks that have exactly one state.",
        "    pub properties: &'static [Property],",
        "}",
        "",
        "/// One block and all of its states.",
        "pub struct BlockDef {",
        "    /// Namespaced identifier, e.g. `minecraft:stone`.",
        "    pub name: &'static str,",
        "    /// The state this block reports when nothing is set.",
        "    pub default_state: u32,",
        "    pub states: &'static [BlockState],",
        "}",
        "",
        "/// One entry per block, in registration order.",
        "pub static BLOCKS: &[BlockDef] = &[",
    ]

    # The report is keyed by identifier, so the key is carried through the
    # loop rather than taken from a field: these entries have no `name`.
    for key, b in data.items():
        states = b.get("states", [])
        default = next(
            (s["id"] for s in states if s.get("default")),
            states[0]["id"] if states else 0,
        )

        props = b.get("properties", {})
        prop_names = list(props.keys())

        # Only one state per block is the overwhelming majority: stone, dirt and
        # glass have a single state and no properties. Those become a unit struct
        # so the common case costs nothing at runtime.
        if len(states) == 1:
            out.append(f"    BlockDef {{")
            out.append(f'        name: "{key}",')
            out.append(f"        default_state: {default},")
            out.append(f"        states: &[BlockState {{ id: {default}, properties: &[] }}],")
            out.append("    },")
            continue

        out.append(f"    BlockDef {{")
        out.append(f'        name: "{key}",')
        out.append(f"        default_state: {default},")
        out.append("        states: &[")
        for s in states:
            if not s.get("properties"):
                out.append(f"            BlockState {{ id: {s['id']}, properties: &[] }},")
                continue
            # Properties are emitted as a fixed array of (name, value) pairs in
            # the order the report lists them, which is the order the client
            # serialises them in.
            pairs = ", ".join(
                f'("{k}", "{s["properties"][k]}")' for k in prop_names
            )
            out.append(
                f"            BlockState {{ id: {s['id']}, "
                f"properties: &[{pairs}] }},"
            )
        out.append("        ],")
        out.append("    },")

    out.append("];")
    return "\n".join(out) + "\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)

    blocks = build_blocks(load(EXTRACTED / "blocks.json"))
    (OUT / "blocks.rs").write_text(blocks, encoding="utf-8")

    print(f"wrote {OUT / 'blocks.rs'} ({len(blocks) / 1024:.0f} KB)")


if __name__ == "__main__":
    main()